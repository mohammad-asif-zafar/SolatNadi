package com.hathway.solatnadi.presentation.theme

import androidx.compose.ui.unit.dp

/**
 * Shared spacing scale. Use these values instead of arbitrary padding
 * throughout screens and reusable components.
 */
object SolatNadiSpacing {
    val None = 0.dp
    val XSmall = 4.dp
    val Small = 8.dp
    val Medium = 12.dp
    val Large = 16.dp
    val XLarge = 20.dp
    val XXLarge = 24.dp
    val Huge = 32.dp
    val XHuge = 40.dp
    val Section = 48.dp
}
